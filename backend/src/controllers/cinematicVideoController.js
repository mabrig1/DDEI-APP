'use strict';
const crypto = require('node:crypto');
const { COURSES } = require('../data/courseCatalog');
const CinematicVideoJob = require('../models/CinematicVideoJob');
const { buildCinematicLesson } = require('../utils/cinematicSwarm');

// Fixed outbound origin: a configured URL is deliberately not accepted to avoid SSRF.
const AIVIDEO_API = 'https://aivideo.mabrigkorie.org/api/video-execution';
const REQUEST_ID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const PROVIDER_JOB_ID = /^[a-zA-Z0-9_-]{1,128}$/;

function configured(env = process.env) {
  return env.DDEI_AIVIDEO_GPU_ENABLED === 'true' &&
    typeof env.DDEI_AIVIDEO_EXECUTION_TOKEN === 'string' &&
    env.DDEI_AIVIDEO_EXECUTION_TOKEN.length >= 32;
}

function catalog(req, res) {
  res.json({
    enabled: configured(),
    provider: 'local-wan',
    costPolicy: 'Owner approval required. No paid video provider is allowed; local GPU compute still consumes resources.',
    renderEnabled: configured(),
    apps: {
      aivideo: 'https://aivideo.mabrigkorie.org',
      vidmint: 'https://vidmint.mabrigkorie.org',
    },
    courses: COURSES.map((course) => ({
      id: course.id,
      title: course.title,
      modules: course.modules.map((module) => ({
        id: module.id,
        title: module.title,
        lessons: module.lessons.map((lesson) => ({ id: lesson.id, title: lesson.title })),
      })),
    })),
  });
}

function trustedScene(courseId, lessonId, sceneIndex) {
  const course = COURSES.find((item) => item.id === courseId);
  if (!course) return null;
  for (const module of course.modules) {
    const lesson = module.lessons.find((item) => item.id === lessonId);
    if (!lesson) continue;
    const studio = buildCinematicLesson(course, module, lesson);
    return { course, module, lesson, scene: studio.scenes[sceneIndex] };
  }
  return null;
}

function scenePrompt(clip) {
  return [
    'Generate one original eight-second visual teaching clip for an approved MABRIG Technologies educational lesson.',
    'Lesson: ' + clip.lesson.title,
    'Concept to illustrate visually: ' + clip.scene.caption,
    'Visual genre: ' + clip.scene.theme + '; camera movement: ' + clip.scene.motion + '.',
    'Use cinematic lighting, smooth original symbolic imagery and clear composition.',
    'No photorealistic likeness of a real person. No brand imitations. No claims, subtitles or readable text generated by the model.',
    'The DDEI player will place the verified caption separately.',
  ].join('\n');
}

async function remote(method, suffix, payload, env = process.env, fetchImpl = globalThis.fetch) {
  if (!configured(env)) throw Object.assign(new Error('Native GPU bridge is disabled or not configured'), { status: 503 });
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 20000);
  try {
    const response = await fetchImpl(AIVIDEO_API + suffix, {
      method,
      redirect: 'manual',
      signal: controller.signal,
      headers: {
        'Authorization': 'Bearer ' + env.DDEI_AIVIDEO_EXECUTION_TOKEN,
        'Content-Type': 'application/json',
        'Accept': 'application/json',
      },
      ...(payload ? { body: JSON.stringify(payload) } : {}),
    });
    if (response.status >= 300 && response.status < 400) throw new Error('Video service redirect rejected');
    if (!response.ok) throw new Error('AIVideo rejected or could not process the request (HTTP ' + response.status + ')');
    const raw = await response.text();
    if (raw.length > 14000) throw new Error('Video service response too large');
    let parsed;
    try { parsed = JSON.parse(raw); } catch (_) { throw new Error('Invalid AIVideo JSON response'); }
    return parsed;
  } finally {
    clearTimeout(timer);
  }
}

function publicRecord(job) {
  return {
    id: job._id,
    courseId: job.courseId,
    lessonId: job.lessonId,
    sceneIndex: job.sceneIndex,
    state: job.state,
    provider: job.provider,
    providerJobId: job.providerJobId || null,
    outputUrls: job.outputUrls || [],
    error: job.error || null,
  };
}

async function startRender(req, res) {
  if (!configured()) return res.status(503).json({
    message: 'The native AIVideo GPU is not connected. Download a real browser clip instead; no provider credits are required.',
  });
  const body = req.body || {};
  const { courseId, lessonId, requestId } = body;
  const index = body.sceneIndex;
  if (body.approveCompute !== true || body.rightsConfirmed !== true) {
    return res.status(400).json({ message: 'Confirm lesson ownership and approve local GPU compute for this scene.' });
  }
  if (typeof courseId !== 'string' || typeof lessonId !== 'string' ||
      courseId.length > 120 || lessonId.length > 120 ||
      !Number.isInteger(index) || index < 0 || index > 3 ||
      typeof requestId !== 'string' || !REQUEST_ID.test(requestId)) {
    return res.status(400).json({ message: 'Valid course, lesson, scene index and unique request ID are required.' });
  }
  const clip = trustedScene(courseId, lessonId, index);
  if (!clip) return res.status(404).json({ message: 'Verified lesson scene not found' });
  const missionId = 'ddei-' + requestId;
  let job;
  try {
    job = await CinematicVideoJob.create({
      _id: requestId, courseId, lessonId, sceneIndex: index, missionId,
      provider: 'local-wan', state: 'submitting',
    });
  } catch (err) {
    if (err.code !== 11000) throw err;
    const existing = await CinematicVideoJob.findById(requestId);
    if (!existing || existing.courseId !== courseId ||
        existing.lessonId !== lessonId || existing.sceneIndex !== index) {
      return res.status(409).json({ message: 'Request ID already belongs to another scene.' });
    }
    return res.status(202).json({ job: publicRecord(existing), duplicate: true });
  }

  try {
    // Strictly the local WAN GPU: never auto-fallback to Gemini Veo, Runway or
    // VidMint's metered Magic Hour provider.
    const result = await remote('POST', '', {
      input: {
        missionId,
        prompt: scenePrompt(clip),
        durationSeconds: 8,
        aspectRatio: '16:9',
        candidateProviderIds: ['local-wan'],
      },
    });
    const sub = result.submission;
    if (sub && sub.providerId === 'local-wan' && PROVIDER_JOB_ID.test(sub.providerJobId || '')) {
      job.providerJobId = sub.providerJobId;
      job.state = 'submitted';
    } else {
      job.state = 'unavailable';
      job.error = 'No local GPU worker accepted this scene. Nothing was charged by a paid video provider.';
    }
  } catch (_) {
    // A timeout is ambiguous: NEVER automatically retry as a GPU job might
    // already have been accepted. Owner must inspect the AIVideo console.
    job.state = 'unknown';
    job.error = 'Submission was not confirmed. Check AIVideo before trying a new request.';
  }
  await job.save();
  return res.status(job.state === 'submitted' ? 202 : 503).json({ job: publicRecord(job) });
}

function permittedOutputs(urls, env = process.env) {
  const allowed = String(env.DDEI_VIDEO_OUTPUT_ALLOWED_HOSTS || '')
    .split(',').map((s) => s.trim().toLowerCase()).filter(Boolean);
  if (!Array.isArray(urls) || !allowed.length) return [];
  return urls.filter((raw) => {
    try {
      const url = new URL(raw);
      return url.protocol === 'https:' && !url.username && !url.password && !url.port &&
        allowed.includes(url.hostname.toLowerCase());
    } catch (_) { return false; }
  }).slice(0, 4);
}

async function renderStatus(req, res) {
  if (!REQUEST_ID.test(req.params.requestId || '')) {
    return res.status(400).json({ message: 'Invalid render job ID' });
  }
  const job = await CinematicVideoJob.findById(req.params.requestId);
  if (!job) return res.status(404).json({ message: 'Render job not found' });
  if (configured() && job.providerJobId && ['submitted', 'working'].includes(job.state)) {
    try {
      const data = await remote('GET', '?providerId=local-wan&providerJobId=' +
        encodeURIComponent(job.providerJobId));
      if (data.providerId === 'local-wan' && data.providerJobId === job.providerJobId) {
        const state = String(data.status || '').toLowerCase();
        if (['working', 'queued'].includes(state)) job.state = 'working';
        if (state === 'succeeded') {
          job.state = 'succeeded';
          job.outputUrls = permittedOutputs(data.outputUrls);
        }
        if (state === 'failed') {
          job.state = 'failed';
          job.error = String(data.error || 'GPU render failed').slice(0, 250);
        }
        await job.save();
      }
    } catch (_) {
      // Do not change a real submitted job into a failed job just because the
      // status API was temporarily unavailable. Return the last saved state.
    }
  }
  return res.json({ job: publicRecord(job) });
}

module.exports = { catalog, startRender, renderStatus, configured, trustedScene, scenePrompt, permittedOutputs, remote };
